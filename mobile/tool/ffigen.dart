import 'dart:io';
import 'package:ffigen/ffigen.dart';

Future<void> main() async {
  final packageRoot = Platform.script.resolve('../');
  final entryHeader = packageRoot.resolve('third_party/huaguruncho_core/huaguruncho_core.h');
  final bindingsOutput = packageRoot.resolve('lib/src/third_party/huaguruncho_core.g.dart');

  Uri? clangUri;
  for (final p in [
    '/Library/Developer/CommandLineTools/usr/lib/libclang.dylib',
    '/Users/miguel/Library/Android/sdk/ndk/28.2.13676358/toolchains/llvm/prebuilt/darwin-x86_64/lib/libclang.dylib',
  ]) {
    if (File(p).existsSync()) {
      clangUri = Uri.file(p);
      break;
    }
  }

  await FfiGenerator(
    input: Input(
      entryPoints: [entryHeader],
      include: (header) => header.path.endsWith('huaguruncho_core.h'),
    ),
    visitors: [
      Visitor(
        func: (node) {
          if (node.originalName.startsWith('h360_')) {
            node.isIncluded = true;
          }
        },
      ),
    ],
    output: Output(
      dart: DartOutput(path: bindingsOutput),
      format: true,
      style: const DynamicLibraryBindings(
        wrapperName: 'HuagurunchoCoreBindings',
        wrapperDocComment: 'FFI bindings to the native Rust huaguruncho_core engine.',
      ),
      preamble: '''
// Copyright (c) 2026 Proyecto Huaguruncho 360 - Municipalidad Distrital de Huachón, Pasco, Perú.
// Licensed under the MIT License.

// AUTO-GENERATED FILE - DO NOT MODIFY.
// Generated by package:ffigen. Do not edit manually.
// To regenerate: dart run tool/ffigen.dart

// ignore_for_file: type=lint, unused_import, unused_element, unused_field, camel_case_types, non_constant_identifier_names, deprecated_member_use_from_same_package, experimental_member_use
''',
    ),
  ).generate(libclangDylib: clangUri);

  stdout.writeln('Successfully generated huaguruncho_core FFI bindings.');
}
